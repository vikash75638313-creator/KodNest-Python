#int
a = 10 
print(type(a), a)

#float
b = -34.45
print(type(b), b)

#complex
c = 10+5j
print(type(c), c)

#string
d = "Vikash"
print(type(d), d)

#boolean
e = True
print(type(e), e)

#list
f = [1, 2, 3, 4, 5]
print(type(f), f)

#tuple
g = (1, 2, 3, 4, 5)
print(type(g), g)

#set
h = {1, 2, 3, 4, 5}
print(type(h), h)

#dict
i = {1: "one", 2: "two", 3: "three", 4: "four", 5: "five"}
print(type(i), i)

#none
j = None
print(type(j), j)